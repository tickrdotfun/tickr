// Rewrites the generated block of docs/18-events-and-errors.md from the compiled artifacts: every event with its
// topic0 and every custom error with its four byte selector, grouped by signature with the contracts that carry
// it. The hashes are computed from the ABIs, never typed, so the table cannot drift from the code.
//
// Runs from sync-docs.mjs when ../contracts/out exists (run `forge build` there first). A checkout without
// artifacts keeps the block it already has. Standalone: node scripts/gen-selectors.mjs
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { toEventSelector, toFunctionSelector } from "viem";

const here = dirname(fileURLToPath(import.meta.url));
const outDir = resolve(here, "..", "..", "contracts", "out");
const doc = resolve(here, "..", "..", "docs", "18-events-and-errors.md");
const START = "<!-- selectors:start -->";
const END = "<!-- selectors:end -->";

// the canonical signature: names dropped, structs spelled out as tuples, arrays kept on the outside
const typeOf = (p) => (p.type.startsWith("tuple") ? `(${p.components.map(typeOf).join(",")})${p.type.slice(5)}` : p.type);
const formatAbiItem = (item) => `${item.name}(${item.inputs.map(typeOf).join(",")})`;

// tickr's own contracts, in the order the docs introduce them, then the one Uniswap contract an indexer reads
const OURS = [
  "Factory",
  "LaunchDeployer",
  "LaunchSeeder",
  "LaunchLocker",
  "FeeEscrow",
  "Token",
  "LaunchAndBuyRouter",
  "TickerLauncher",
  "ManagedTickerToken",
  "ManagedTickerHook",
  "ManagedTickerDeployer",
  "AnchorRegistry",
  "StockQuoteLauncher",
  "CoinQuoteLauncher",
  "MarketQuoteLauncher",
  "ZapRouter",
  "BuybackTreasury",
  "BuybackVault",
];
const UNISWAP = { name: "PoolManager", events: ["Initialize", "ModifyLiquidity", "Swap"] };

export function generate() {
  if (!existsSync(outDir) || !existsSync(doc)) return false;
  const events = new Map(); // signature -> { selector, by: Set }
  const errors = new Map();
  const add = (map, item, by) => {
    const sig = formatAbiItem(item);
    const cur = map.get(sig) ?? { selector: item.type === "event" ? toEventSelector(sig) : toFunctionSelector(sig), by: new Set() };
    cur.by.add(by);
    map.set(sig, cur);
  };
  const abiOf = (name) => {
    const file = join(outDir, `${name}.sol`, `${name}.json`);
    return existsSync(file) ? JSON.parse(readFileSync(file, "utf8")).abi : undefined;
  };
  for (const name of OURS) {
    const abi = abiOf(name);
    if (!abi) {
      console.warn(`selectors: no artifact for ${name}, skipped`);
      continue;
    }
    for (const item of abi) {
      if (item.type === "event") add(events, item, name);
      if (item.type === "error") add(errors, item, name);
    }
  }
  const pm = abiOf(UNISWAP.name);
  if (pm) for (const item of pm) if (item.type === "event" && UNISWAP.events.includes(item.name)) add(events, item, `Uniswap ${UNISWAP.name}`);

  const rows = (map) =>
    [...map.entries()]
      .sort(([a], [b]) => a.localeCompare(b))
      .map(([sig, { selector, by }]) => `| \`${sig}\` | \`${selector}\` | ${[...by].join(", ")} |`)
      .join("\n");
  const block =
    `${START}\n` +
    `<!-- generated by web/scripts/gen-selectors.mjs from contracts/out. do not edit by hand. -->\n\n` +
    `### Events\n\n| event | topic0 | emitted by |\n| --- | --- | --- |\n${rows(events)}\n\n` +
    `### Errors\n\n| error | selector | declared in |\n| --- | --- | --- |\n${rows(errors)}\n` +
    `${END}`;

  const md = readFileSync(doc, "utf8");
  const a = md.indexOf(START);
  const b = md.indexOf(END);
  if (a < 0 || b < 0 || b < a) throw new Error(`selectors: ${doc} has no ${START} ... ${END} block`);
  const next = md.slice(0, a) + block + md.slice(b + END.length);
  if (next !== md) writeFileSync(doc, next);
  console.log(`selectors: ${events.size} events, ${errors.size} errors ${next !== md ? "written to" : "unchanged in"} docs/18-events-and-errors.md`);
  return true;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (!generate()) console.log("selectors: contracts/out or docs/18 not found, nothing generated");
}
